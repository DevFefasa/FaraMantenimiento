-- 12_ticket_tablas.sql
-- Tablas de tickets (historial, materiales, encuesta, comentarios)
-- Sin FOREIGN KEY hacia usuario: solo índices en fiUsuarioId / fiSolicitanteId / auditoría
-- Aplicar: docker exec -i MariaLocal sh -c 'mariadb -uroot -p"$MARIADB_ROOT_PASSWORD" faramantenimiento' < db/migrations/12_ticket_tablas.sql

SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS ticket (
  fiId INT NOT NULL AUTO_INCREMENT,
  fcNumero VARCHAR(30) NOT NULL COMMENT 'TK-AAAA-000001',
  fdFechaIngreso DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fiSolicitanteId INT NULL COMMENT 'Sin FK a usuario; solo índice',
  fcSolicitanteNombre VARCHAR(150) NOT NULL,
  fcCargo VARCHAR(100) NULL,
  fcCorreo VARCHAR(150) NULL,
  fcTelefono VARCHAR(40) NULL,
  fiSucursalId INT NOT NULL,
  fiUbicacionId INT NULL,
  fcUbicacionDetalle VARCHAR(250) NULL,
  fiActivoId INT NULL,
  fiTipoMantenimientoId INT NOT NULL,
  fiCategoriaId INT NOT NULL,
  fiPrioridadId INT NOT NULL,
  fcDescripcion TEXT NOT NULL,
  fdFechaSugerida DATETIME NULL,
  fiEstadoId INT NOT NULL,
  fiMotivoEsperaId INT NULL,
  fcTipoResponsable VARCHAR(20) NULL COMMENT 'INTERNO o PROVEEDOR',
  fiTecnicoId INT NULL,
  fiProveedorId INT NULL,
  fdFechaProgramada DATETIME NULL,
  fdFechaInicio DATETIME NULL,
  fdFechaFin DATETIME NULL,
  fnHorasTrabajadas DECIMAL(10,2) NULL,
  fnCostoManoObra DECIMAL(14,2) NULL,
  fnCostoMateriales DECIMAL(14,2) NULL,
  fnCostoProveedor DECIMAL(14,2) NULL,
  fcDiagnostico TEXT NULL,
  fcCausaRaiz TEXT NULL,
  fcTrabajoRealizado TEXT NULL,
  fcAccionesPreventivas TEXT NULL,
  fbReincidencia TINYINT(1) NOT NULL DEFAULT 0,
  fiTicketReincidenteId INT NULL,
  fdLimiteRespuesta DATETIME NULL,
  fdLimiteSolucion DATETIME NULL,
  fdPrimeraRespuesta DATETIME NULL,
  fdResuelto DATETIME NULL,
  fdValidado DATETIME NULL,
  fdCerrado DATETIME NULL,
  fdInicioEspera DATETIME NULL,
  fiMinutosEnEspera INT NOT NULL DEFAULT 0,
  fbSlaRespuestaCumplido TINYINT(1) NULL,
  fbSlaSolucionCumplido TINYINT(1) NULL,
  fbCierreAutomatico TINYINT(1) NOT NULL DEFAULT 0,
  fdCreado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fiCreadoPor INT NULL,
  fdModificado DATETIME NULL,
  fiModificadoPor INT NULL,
  fbActivo TINYINT(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (fiId),
  UNIQUE KEY uk_ticket_numero (fcNumero),
  KEY ix_ticket_fecha (fdFechaIngreso),
  KEY ix_ticket_sucursal (fiSucursalId),
  KEY ix_ticket_estado (fiEstadoId),
  KEY ix_ticket_prioridad (fiPrioridadId),
  KEY ix_ticket_activo_categoria (fiActivoId, fiCategoriaId),
  KEY ix_ticket_tipo (fiTipoMantenimientoId),
  KEY ix_ticket_solicitante (fiSolicitanteId),
  KEY ix_ticket_tecnico (fiTecnicoId),
  KEY ix_ticket_proveedor (fiProveedorId),
  KEY ix_ticket_ubicacion (fiUbicacionId),
  KEY ix_ticket_motivoespera (fiMotivoEsperaId),
  KEY ix_ticket_reincidente (fiTicketReincidenteId),
  KEY ix_ticket_creadopor (fiCreadoPor),
  KEY ix_ticket_modificadopor (fiModificadoPor),
  KEY ix_ticket_activo_flag (fbActivo),
  CONSTRAINT fk_ticket_sucursal FOREIGN KEY (fiSucursalId) REFERENCES sucursal (fiId),
  CONSTRAINT fk_ticket_ubicacion FOREIGN KEY (fiUbicacionId) REFERENCES ubicacion (fiId),
  CONSTRAINT fk_ticket_activo FOREIGN KEY (fiActivoId) REFERENCES activo (fiId),
  CONSTRAINT fk_ticket_tipo FOREIGN KEY (fiTipoMantenimientoId) REFERENCES tipomantenimiento (fiId),
  CONSTRAINT fk_ticket_categoria FOREIGN KEY (fiCategoriaId) REFERENCES categoria (fiId),
  CONSTRAINT fk_ticket_prioridad FOREIGN KEY (fiPrioridadId) REFERENCES prioridad (fiId),
  CONSTRAINT fk_ticket_estado FOREIGN KEY (fiEstadoId) REFERENCES estado (fiId),
  CONSTRAINT fk_ticket_motivoespera FOREIGN KEY (fiMotivoEsperaId) REFERENCES motivoespera (fiId),
  CONSTRAINT fk_ticket_tecnico FOREIGN KEY (fiTecnicoId) REFERENCES tecnico (fiId),
  CONSTRAINT fk_ticket_proveedor FOREIGN KEY (fiProveedorId) REFERENCES proveedor (fiId),
  CONSTRAINT fk_ticket_reincidente FOREIGN KEY (fiTicketReincidenteId) REFERENCES ticket (fiId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ticketestado (
  fiId INT NOT NULL AUTO_INCREMENT,
  fiTicketId INT NOT NULL,
  fiEstadoAnteriorId INT NULL,
  fiEstadoId INT NOT NULL,
  fiMotivoEsperaId INT NULL,
  fcComentario VARCHAR(500) NULL,
  fiUsuarioId INT NULL COMMENT 'Sin FK a usuario; solo índice',
  fdFecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (fiId),
  KEY ix_ticketestado_ticket (fiTicketId),
  KEY ix_ticketestado_fecha (fdFecha),
  KEY ix_ticketestado_estado (fiEstadoId),
  KEY ix_ticketestado_usuario (fiUsuarioId),
  KEY ix_ticketestado_motivoespera (fiMotivoEsperaId),
  CONSTRAINT fk_ticketestado_ticket FOREIGN KEY (fiTicketId) REFERENCES ticket (fiId),
  CONSTRAINT fk_ticketestado_anterior FOREIGN KEY (fiEstadoAnteriorId) REFERENCES estado (fiId),
  CONSTRAINT fk_ticketestado_estado FOREIGN KEY (fiEstadoId) REFERENCES estado (fiId),
  CONSTRAINT fk_ticketestado_motivo FOREIGN KEY (fiMotivoEsperaId) REFERENCES motivoespera (fiId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ticketmaterial (
  fiId INT NOT NULL AUTO_INCREMENT,
  fiTicketId INT NOT NULL,
  fcDescripcion VARCHAR(250) NOT NULL,
  fnCantidad DECIMAL(12,2) NOT NULL DEFAULT 1.00,
  fcUnidad VARCHAR(30) NULL,
  fnCostoUnitario DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  fnTotal DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  fdCreado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fiCreadoPor INT NULL,
  fdModificado DATETIME NULL,
  fiModificadoPor INT NULL,
  fbActivo TINYINT(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (fiId),
  KEY ix_ticketmaterial_ticket (fiTicketId),
  KEY ix_ticketmaterial_activo (fbActivo),
  KEY ix_ticketmaterial_creadopor (fiCreadoPor),
  CONSTRAINT fk_ticketmaterial_ticket FOREIGN KEY (fiTicketId) REFERENCES ticket (fiId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ticketencuesta (
  fiId INT NOT NULL AUTO_INCREMENT,
  fiTicketId INT NOT NULL,
  fiCalificacion TINYINT NOT NULL COMMENT '1 a 5',
  fbConforme TINYINT(1) NOT NULL DEFAULT 1,
  fcComentario VARCHAR(500) NULL,
  fdFecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fiUsuarioId INT NULL COMMENT 'Sin FK a usuario; solo índice',
  PRIMARY KEY (fiId),
  UNIQUE KEY uk_ticketencuesta_ticket (fiTicketId),
  KEY ix_ticketencuesta_calificacion (fiCalificacion),
  KEY ix_ticketencuesta_usuario (fiUsuarioId),
  CONSTRAINT fk_ticketencuesta_ticket FOREIGN KEY (fiTicketId) REFERENCES ticket (fiId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ticketcomentario (
  fiId INT NOT NULL AUTO_INCREMENT,
  fiTicketId INT NOT NULL,
  fcComentario TEXT NOT NULL,
  fbInterno TINYINT(1) NOT NULL DEFAULT 0 COMMENT '1 = solo visible para mantenimiento/jefatura',
  fiUsuarioId INT NULL COMMENT 'Sin FK a usuario; solo índice',
  fdFecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fbActivo TINYINT(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (fiId),
  KEY ix_ticketcomentario_ticket (fiTicketId),
  KEY ix_ticketcomentario_fecha (fdFecha),
  KEY ix_ticketcomentario_usuario (fiUsuarioId),
  KEY ix_ticketcomentario_activo (fbActivo),
  CONSTRAINT fk_ticketcomentario_ticket FOREIGN KEY (fiTicketId) REFERENCES ticket (fiId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
